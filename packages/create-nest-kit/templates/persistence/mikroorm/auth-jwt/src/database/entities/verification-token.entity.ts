import {
  Entity,
  Index,
  ManyToOne,
  PrimaryKey,
  Property,
  Unique,
} from '@mikro-orm/decorators/legacy';
import type {
  NewVerificationToken,
  VerificationPurpose,
} from '../../auth/verification-tokens.repository.js';
import { UserEntity } from './user.entity.js';

@Entity({ tableName: 'verification_tokens' })
@Unique({ name: 'verification_tokens_token_hash_unique', properties: ['tokenHash'] })
// By user and purpose to replace a user's tokens; by expiry for the daily purge.
@Index({ name: 'verification_tokens_user_id_purpose_index', properties: ['userId', 'purpose'] })
@Index({ name: 'verification_tokens_expires_at_index', properties: ['expiresAt'] })
export class VerificationTokenEntity implements NewVerificationToken {
  /** A UUIDv7 generated by the repository. */
  @PrimaryKey({ type: 'uuid' })
  id!: string;

  /** The user's id (`mapToPk`), not the user entity. */
  @ManyToOne(() => UserEntity, {
    mapToPk: true,
    fieldName: 'user_id',
    deleteRule: 'cascade',
    foreignKeyName: 'verification_tokens_user_id_users_id_fk',
  })
  userId!: string;

  @Property({ type: 'text' })
  purpose!: VerificationPurpose;

  @Property({ type: 'text' })
  tokenHash!: string;

  @Property({ type: 'datetime' })
  expiresAt!: Date;

  @Property({ type: 'datetime' })
  createdAt!: Date;
}
