import { Column, Entity, ForeignKey, Index, PrimaryColumn, Unique } from 'typeorm';
import type {
  NewVerificationToken,
  VerificationPurpose,
} from '../../auth/verification-tokens.repository.js';
import { UserEntity } from './user.entity.js';

@Entity({ name: 'verification_tokens' })
@Unique('verification_tokens_token_hash_unique', ['tokenHash'])
// By user and purpose to replace a user's tokens; by expiry for the daily purge.
@Index('verification_tokens_user_id_purpose_index', ['userId', 'purpose'])
@Index('verification_tokens_expires_at_index', ['expiresAt'])
export class VerificationTokenEntity implements NewVerificationToken {
  /** A UUIDv7 generated by the repository. */
  @PrimaryColumn({ type: 'uuid', primaryKeyConstraintName: 'verification_tokens_pkey' })
  id!: string;

  @Column({ name: 'user_id', type: 'uuid' })
  @ForeignKey(() => UserEntity, {
    name: 'verification_tokens_user_id_users_id_fk',
    onDelete: 'CASCADE',
  })
  userId!: string;

  @Column({ type: 'text' })
  purpose!: VerificationPurpose;

  @Column({ name: 'token_hash', type: 'text' })
  tokenHash!: string;

  @Column({ name: 'expires_at', type: 'timestamptz' })
  expiresAt!: Date;

  @Column({ name: 'created_at', type: 'timestamptz' })
  createdAt!: Date;
}
